/**
 * generate-employee-ad-map.mjs
 *
 * Queries all active employees from the DB, resolves each one to an AD account
 * via the adsearch sidecar (same lookup path the app uses), then outputs:
 *
 *   set-employee-ids.ps1    — PowerShell script for AD admin to run
 *   employee-ad-map.csv     — full mapping report (matched + unmatched)
 *
 * Usage (run on the server where the app runs):
 *   node generate-employee-ad-map.mjs
 *
 * Requires the .env file in the same directory (DB + sidecar config).
 */

import 'dotenv/config';
import { writeFileSync } from 'fs';
import sequelize from './src/config/database.js';
import Employee  from './src/models/Employee.js';
import { findUserByEmail, searchUsersByName } from './src/services/adService.js';

// ── Helpers ────────────────────────────────────────────────────────────────────
const sleep = ms => new Promise(r => setTimeout(r, ms));

function csvEscape(v) {
    return `"${String(v ?? '').replace(/"/g, '""')}"`;
}

// ── Main ───────────────────────────────────────────────────────────────────────
async function main() {
    await sequelize.authenticate();
    console.log('[DB] Connected.\n');

    const employees = await Employee.findAll({
        where:      { status: 'Active' },
        attributes: ['employeeId', 'name', 'email', 'mainDept', 'location'],
        order:      [['employeeId', 'ASC']]
    });

    console.log(`[DB] Found ${employees.length} active employees.\n`);

    const matched   = [];
    const unmatched = [];
    let   i         = 0;

    for (const emp of employees) {
        i++;
        process.stdout.write(`\r[${i}/${employees.length}] ${emp.employeeId} – ${emp.name}…          `);

        if (!emp.email) {
            unmatched.push({ emp, reason: 'No email in DB' });
            continue;
        }

        let adUser = null;

        // Strategy 1: exact email lookup
        try {
            adUser = await findUserByEmail(emp.email);
        } catch (_) {}

        // Strategy 2: name search fallback (first token of name)
        if (!adUser && emp.name) {
            try {
                const results = await searchUsersByName(emp.name.split(' ')[0]);
                // Find the result whose email matches
                const hit = results.find(r =>
                    (r.mail || r.email || '').toLowerCase() === emp.email.toLowerCase()
                );
                if (hit) adUser = hit;
            } catch (_) {}
        }

        if (adUser && adUser.sAMAccountName) {
            matched.push({
                employeeId:     emp.employeeId,
                name:           emp.name,
                dbEmail:        emp.email,
                dept:           emp.mainDept,
                sAMAccountName: adUser.sAMAccountName,
                adEmail:        adUser.mail || adUser.email || '',
                adDisplayName:  adUser.displayName || ''
            });
        } else {
            unmatched.push({ emp, reason: 'Not found in AD (tried email + name search)' });
        }

        // Throttle — avoid hammering the sidecar
        await sleep(150);
    }

    process.stdout.write('\n\n');

    // ── PowerShell script ────────────────────────────────────────────────────────
    const now = new Date().toISOString();
    const psLines = [
        '#Requires -Module ActiveDirectory',
        '',
        '# ============================================================',
        '#  Set-Employee-IDs.ps1',
        '#  Auto-generated by IFL Workflow — generate-employee-ad-map.mjs',
        `#  Generated : ${now}`,
        `#  Matched   : ${matched.length} employees`,
        `#  Unmatched : ${unmatched.length} employees (see bottom)`,
        '# ============================================================',
        '#',
        '# INSTRUCTIONS FOR AD ADMIN:',
        '#   1. Review the list below — confirm sAMAccountName matches the employee.',
        '#   2. Run this script as a Domain Admin (or account with Write on User objects).',
        '#   3. The script sets the "Employee ID" (employeeID) attribute on each user.',
        '#   4. After running, reply so the IFL Workflow app can be updated to match',
        '#      DB employees to AD accounts via this field.',
        '#',
        '# ============================================================',
        '',
        '$ErrorActionPreference = "Continue"',
        '$results = @()',
        '',
        '# ── Matched employees ───────────────────────────────────────',
        ...matched.map(m => [
            '',
            `# ${m.name} | DB email: ${m.dbEmail} | Dept: ${m.dept || 'N/A'}`,
            `try {`,
            `    Set-ADUser -Identity "${m.sAMAccountName}" -EmployeeID "${m.employeeId}"`,
            `    $results += [PSCustomObject]@{ EmployeeId="${m.employeeId}"; SAM="${m.sAMAccountName}"; Status="OK" }`,
            `    Write-Host "OK  ${m.employeeId}  ${m.sAMAccountName}" -ForegroundColor Green`,
            `} catch {`,
            `    $results += [PSCustomObject]@{ EmployeeId="${m.employeeId}"; SAM="${m.sAMAccountName}"; Status="FAIL: $_" }`,
            `    Write-Host "ERR ${m.employeeId}  ${m.sAMAccountName}: $_" -ForegroundColor Red`,
            `}`,
        ].join('\n')),
        '',
        '# ── Summary ─────────────────────────────────────────────────',
        '',
        '$results | Format-Table -AutoSize',
        `Write-Host ""`,
        `Write-Host "Done. $($results.Where({$_.Status -eq 'OK'}).Count) set, $($results.Where({$_.Status -ne 'OK'}).Count) failed." -ForegroundColor Cyan`,
        '',
        '# ── Unmatched (manual action needed) ────────────────────────',
        ...( unmatched.length ? [
            '',
            '# The following employees could NOT be automatically matched to an AD account.',
            '# Please locate the correct sAMAccountName for each and add manually:',
            '',
            ...unmatched.map(({ emp, reason }) =>
                `# UNMATCHED | EmployeeID: ${emp.employeeId} | Name: ${emp.name} | Email: ${emp.email || 'N/A'} | Reason: ${reason}`
            )
        ] : ['', '# All employees were successfully matched — no manual action needed.']),
    ];

    writeFileSync('set-employee-ids.ps1', psLines.join('\n'), 'utf8');

    // ── CSV report ───────────────────────────────────────────────────────────────
    const csvHeader = ['EmployeeID', 'Name', 'DB_Email', 'Department', 'sAMAccountName', 'AD_Email', 'AD_DisplayName', 'Matched', 'Notes'];
    const csvRows   = [
        ...matched.map(m => [
            m.employeeId, m.name, m.dbEmail, m.dept,
            m.sAMAccountName, m.adEmail, m.adDisplayName, 'YES', ''
        ]),
        ...unmatched.map(({ emp, reason }) => [
            emp.employeeId, emp.name, emp.email || '', emp.mainDept || '',
            '', '', '', 'NO', reason
        ])
    ];

    const csv = [
        csvHeader.map(csvEscape).join(','),
        ...csvRows.map(row => row.map(csvEscape).join(','))
    ].join('\n');

    writeFileSync('employee-ad-map.csv', csv, 'utf8');

    // ── Summary ──────────────────────────────────────────────────────────────────
    console.log('━'.repeat(60));
    console.log(`✅  Matched   : ${matched.length} employees`);
    console.log(`⚠️   Unmatched : ${unmatched.length} employees`);
    console.log('━'.repeat(60));
    console.log('\nFiles written:');
    console.log('  📄 set-employee-ids.ps1    — send this to your AD admin');
    console.log('  📊 employee-ad-map.csv     — full mapping report\n');

    if (unmatched.length) {
        console.log('Unmatched employees (need manual lookup):');
        unmatched.forEach(({ emp, reason }) =>
            console.log(`  • ${emp.employeeId}  ${emp.name}  <${emp.email || 'no email'}>  — ${reason}`)
        );
        console.log('');
    }

    await sequelize.close();
}

main().catch(err => {
    console.error('\n[ERROR]', err.message);
    process.exit(1);
});
